#!/usr/bin/env python3
"""Prepare ICSx5 (GPL-3.0) for the SableOS image (owner decision 2026-11-12).

ICSx5 subscribes to calendar links (.ics), such as a published Outlook.com or Microsoft 365
calendar, and keeps them in Android's calendar store, read-only, for Sable Calendar. SableOS ships it
unchanged from the pinned tag v2.4.3; the only edit is the release signing: upstream signs with
Bitfire's key from the environment, and the platform build signs SableOS apps.
"""

from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from sable_flavor_common import SABLE_DARK, SABLE_LIGHT, check_commit, sable_scheme, set_sable_icon  # noqa: E402

EXPECTED_COMMIT = "81036b50c10d331ec13fc107f5beae5ca32b72de"
SIGNING = (
    '            productFlavors.getByName("standard").signingConfig = signingConfigs.getByName("bitfire_apk")\n',
    '            productFlavors.getByName("gplay").signingConfig = signingConfigs.getByName("bitfire_aab")\n',
)


def fail(message: str) -> None:
    raise SystemExit(message)


def apply_colours(root: pathlib.Path) -> None:
    """ICSx5's blues become the Sable colours, dark and light; its screens otherwise stay upstream's."""
    theme = root / "app/src/main/java/at/bitfire/icsdroid/ui/theme/Theme.kt"
    text = theme.read_text(encoding="utf-8")
    start = text.find("private val DarkColors = darkColorScheme(")
    end = text.find("\n@Composable\nfun AppTheme(")
    anchor = "import androidx.compose.runtime.getValue\n"
    if start < 0 or end < start or text.count(anchor) != 1:
        fail("SABLE_ICSX5_COLOURS=FAIL")
    schemes = (
        "// SableOS: the Sable colours in place of ICSx5's (sable-src/apps/r8/icsx5/apply_sable_flavor.py).\n"
        f"private val DarkColors = {sable_scheme('darkColorScheme', SABLE_DARK, '')}\n\n"
        f"private val LightColors = {sable_scheme('lightColorScheme', SABLE_LIGHT, '')}\n"
    )
    text = text[:start] + schemes + text[end:]
    text = text.replace(anchor, anchor + "import androidx.compose.ui.graphics.Color\n", 1)
    theme.write_text(text, encoding="utf-8")


def main() -> None:
    if len(sys.argv) != 2:
        fail("usage: apply_sable_flavor.py <icsx5-checkout>")
    root = pathlib.Path(sys.argv[1]).resolve()
    check_commit(root, EXPECTED_COMMIT, "SABLE_ICSX5")
    build = root / "app/build.gradle.kts"
    text = build.read_text(encoding="utf-8")
    for line in SIGNING:
        if text.count(line) != 1:
            fail("SABLE_ICSX5_SIGNING=FAIL")
        text = text.replace(line, "", 1)
    build.write_text(text, encoding="utf-8")
    # Sets android:icon="@mipmap/ic_sable_icsx5" and android:roundIcon="@mipmap/ic_sable_icsx5_round".
    # Icon generated by sable-src/tools/gen_first_party_icons.py (row icsx5); "@string/app_name" stays.
    icons = set_sable_icon(pathlib.Path(__file__).resolve().parent / "res", root / "app", "ic_sable_icsx5", "SABLE_ICSX5")
    apply_colours(root)
    print(f"SABLE_ICSX5_FLAVOR=PASS icons={icons}")


if __name__ == "__main__":
    main()
