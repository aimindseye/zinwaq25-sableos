#!/usr/bin/env python3
"""Prepare ICSx5 (GPL-3.0) for the SableOS image (owner decision 2026-11-12).

ICSx5 subscribes to calendar links (.ics), such as a published Outlook.com or Microsoft 365
calendar, and keeps them in Android's calendar store, read-only, for Sable Calendar. SableOS ships it
unchanged from the pinned tag v2.4.3; the only edit is the release signing: upstream signs with
Bitfire's key from the environment, and the platform build signs SableOS apps.
"""

from __future__ import annotations

import pathlib
import shutil
import subprocess
import sys

EXPECTED_COMMIT = "81036b50c10d331ec13fc107f5beae5ca32b72de"
SIGNING = (
    '            productFlavors.getByName("standard").signingConfig = signingConfigs.getByName("bitfire_apk")\n',
    '            productFlavors.getByName("gplay").signingConfig = signingConfigs.getByName("bitfire_aab")\n',
)


def fail(message: str) -> None:
    raise SystemExit(message)


def apply_icon(root: pathlib.Path) -> int:
    """Give the app the Sable launcher icon; its name (@string/app_name) stays upstream's."""
    # Generated by sable-src/tools/gen_first_party_icons.py (row icsx5).
    source = pathlib.Path(__file__).resolve().parent / "res"
    target = root / "app/src/main/res"
    files = sorted(path for path in source.rglob("*") if path.is_file())
    for path in files:
        destination = target / path.relative_to(source)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, destination)
    manifest = root / "app/src/main/AndroidManifest.xml"
    text = manifest.read_text(encoding="utf-8")
    old = 'android:icon="@mipmap/ic_launcher"'
    if text.count(old) != 1 or "android:roundIcon" in text:
        fail("SABLE_ICSX5_ICON=FAIL")
    new = 'android:icon="@mipmap/ic_sable_icsx5"\n        android:roundIcon="@mipmap/ic_sable_icsx5_round"'
    manifest.write_text(text.replace(old, new, 1), encoding="utf-8")
    return len(files)


def main() -> None:
    if len(sys.argv) != 2:
        fail("usage: apply_sable_flavor.py <icsx5-checkout>")
    root = pathlib.Path(sys.argv[1]).resolve()
    actual = subprocess.check_output(["git", "-C", str(root), "rev-parse", "HEAD"], text=True).strip()
    if actual != EXPECTED_COMMIT:
        fail(f"SABLE_ICSX5_UPSTREAM_COMMIT=FAIL expected={EXPECTED_COMMIT} actual={actual}")
    build = root / "app/build.gradle.kts"
    text = build.read_text(encoding="utf-8")
    for line in SIGNING:
        if text.count(line) != 1:
            fail("SABLE_ICSX5_SIGNING=FAIL")
        text = text.replace(line, "", 1)
    build.write_text(text, encoding="utf-8")
    icons = apply_icon(root)
    print(f"SABLE_ICSX5_FLAVOR=PASS icons={icons}")


if __name__ == "__main__":
    main()
