#!/usr/bin/env python3
"""Prepare DAVx5 (open source edition, GPL-3.0) for the SableOS image (owner decision 2026-11-12).

DAVx5 syncs CalDAV and CardDAV accounts (Google, iCloud, Yahoo, Fastmail, Nextcloud) into Android's
calendar and contacts stores, which Sable Calendar and Sable Phone read. SableOS ships it unchanged
from the pinned tag v4.5.21-ose; the only edit is the release signing: upstream signs with Bitfire's
key from the environment, and the platform build signs SableOS apps, so the release APK is unsigned.
"""

from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from sable_flavor_common import SABLE_DARK, SABLE_LIGHT, check_commit, sable_scheme, set_sable_icon  # noqa: E402

EXPECTED_COMMIT = "f07633b0bb2482aec5cdfe6bd63c9a4b12b4faa2"


def fail(message: str) -> None:
    raise SystemExit(message)


def apply_colours(root: pathlib.Path) -> None:
    """DAVx5's green and orange become the Sable colours; its screens otherwise stay upstream's."""
    theme = root / "core/src/main/kotlin/at/bitfire/davdroid/ui/OseTheme.kt"
    if "object OseTheme {" not in theme.read_text(encoding="utf-8"):
        fail("SABLE_DAVX5_COLOURS=FAIL")
    theme.write_text(
        "package at.bitfire.davdroid.ui\n\n"
        "import androidx.compose.material3.darkColorScheme\n"
        "import androidx.compose.material3.lightColorScheme\n"
        "import androidx.compose.ui.graphics.Color\n\n"
        "// SableOS: the Sable colours in place of DAVx5's (sable-src/apps/r8/davx5/apply_sable_flavor.py).\n"
        "object OseTheme {\n"
        f"    val lightScheme = {sable_scheme('lightColorScheme', SABLE_LIGHT, '    ')}\n\n"
        f"    val darkScheme = {sable_scheme('darkColorScheme', SABLE_DARK, '    ')}\n"
        "}\n",
        encoding="utf-8",
    )


def main() -> None:
    if len(sys.argv) != 2:
        fail("usage: apply_sable_flavor.py <davx5-checkout>")
    root = pathlib.Path(sys.argv[1]).resolve()
    check_commit(root, EXPECTED_COMMIT, "SABLE_DAVX5")
    build = root / "app-ose/build.gradle.kts"
    text = build.read_text(encoding="utf-8")
    line = '            signingConfig = signingConfigs.findByName("bitfire")\n'
    if text.count(line) != 1:
        fail("SABLE_DAVX5_SIGNING=FAIL")
    build.write_text(text.replace(line, "            // SableOS: unsigned; the platform build signs it.\n", 1), encoding="utf-8")
    # Sets android:icon="@mipmap/ic_sable_davx5" and android:roundIcon="@mipmap/ic_sable_davx5_round".
    # Icon generated by sable-src/tools/gen_first_party_icons.py (row davx5); "@string/app_name" stays.
    icons = set_sable_icon(pathlib.Path(__file__).resolve().parent / "res", root / "core", "ic_sable_davx5", "SABLE_DAVX5")
    apply_colours(root)
    print(f"SABLE_DAVX5_FLAVOR=PASS icons={icons}")


if __name__ == "__main__":
    main()
