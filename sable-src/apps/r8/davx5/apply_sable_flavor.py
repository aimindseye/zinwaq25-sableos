#!/usr/bin/env python3
"""Prepare DAVx5 (open source edition, GPL-3.0) for the SableOS image (owner decision 2026-11-12).

DAVx5 syncs CalDAV and CardDAV accounts (Google, iCloud, Yahoo, Fastmail, Nextcloud) into Android's
calendar and contacts stores, which Sable Calendar and Sable Phone read. SableOS ships it unchanged
from the pinned tag v4.5.21-ose; the only edit is the release signing: upstream signs with Bitfire's
key from the environment, and the platform build signs SableOS apps, so the release APK is unsigned.
"""

from __future__ import annotations

import pathlib
import shutil
import subprocess
import sys

EXPECTED_COMMIT = "f07633b0bb2482aec5cdfe6bd63c9a4b12b4faa2"


def fail(message: str) -> None:
    raise SystemExit(message)


def apply_icon(root: pathlib.Path) -> int:
    """Give the app the Sable launcher icon; its name (@string/app_name) stays upstream's."""
    # Generated by sable-src/tools/gen_first_party_icons.py (row davx5).
    source = pathlib.Path(__file__).resolve().parent / "res"
    target = root / "core/src/main/res"
    files = sorted(path for path in source.rglob("*") if path.is_file())
    for path in files:
        destination = target / path.relative_to(source)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, destination)
    manifest = root / "core/src/main/AndroidManifest.xml"
    text = manifest.read_text(encoding="utf-8")
    old = 'android:icon="@mipmap/ic_launcher"'
    if text.count(old) != 1 or "android:roundIcon" in text:
        fail("SABLE_DAVX5_ICON=FAIL")
    new = 'android:icon="@mipmap/ic_sable_davx5"\n        android:roundIcon="@mipmap/ic_sable_davx5_round"'
    manifest.write_text(text.replace(old, new, 1), encoding="utf-8")
    return len(files)


def main() -> None:
    if len(sys.argv) != 2:
        fail("usage: apply_sable_flavor.py <davx5-checkout>")
    root = pathlib.Path(sys.argv[1]).resolve()
    actual = subprocess.check_output(["git", "-C", str(root), "rev-parse", "HEAD"], text=True).strip()
    if actual != EXPECTED_COMMIT:
        fail(f"SABLE_DAVX5_UPSTREAM_COMMIT=FAIL expected={EXPECTED_COMMIT} actual={actual}")
    build = root / "app-ose/build.gradle.kts"
    text = build.read_text(encoding="utf-8")
    line = '            signingConfig = signingConfigs.findByName("bitfire")\n'
    if text.count(line) != 1:
        fail("SABLE_DAVX5_SIGNING=FAIL")
    build.write_text(text.replace(line, "            // SableOS: unsigned; the platform build signs it.\n", 1), encoding="utf-8")
    icons = apply_icon(root)
    print(f"SABLE_DAVX5_FLAVOR=PASS icons={icons}")


if __name__ == "__main__":
    main()
