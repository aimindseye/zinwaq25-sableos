#!/usr/bin/env python3
"""Prepare Key Mapper (GPL-3.0) for the SableOS image (owner request 2026-11-13).

Key Mapper remaps keys and buttons, and adds long-press and double-press actions, through an
accessibility service the person turns on. It suits the Q25's keyboard. SableOS ships it unchanged
from the pinned tag v4.7.0 (the commit F-Droid builds), with the two edits F-Droid's recipe makes:

- the release build no longer signs with the maintainer's keystore (the platform build signs it);
- the dead Bintray repository is dropped from settings.gradle.kts.

Building it needs Rust (rustup, with the four Android targets) and NDK 27.3.13750724 for its evdev
module, as F-Droid's recipe does. It wears the Sable icon; its name stays upstream's; .github/workflows/android.yml installs both for this flavor.
"""

from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from sable_flavor_common import check_commit, set_sable_app_icon  # noqa: E402

EXPECTED_COMMIT = "88bd1f98fcda130694531dff6dd67c92cab42e97"
SIGNING = '            signingConfig = signingConfigs.getByName("release")\n            versionNameSuffix = "-foss"\n'
BINTRAY = '        maven { url = uri("https://dl.bintray.com/rikkaw/Shizuku") }\n'


def replace_once(path: pathlib.Path, old: str, new: str, marker: str) -> None:
    text = path.read_text(encoding="utf-8")
    if text.count(old) != 1:
        raise SystemExit(f"{marker}=FAIL")
    path.write_text(text.replace(old, new, 1), encoding="utf-8")


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: apply_sable_flavor.py <keymapper-checkout>")
    root = pathlib.Path(sys.argv[1]).resolve()
    check_commit(root, EXPECTED_COMMIT, "SABLE_KEYMAPPER")
    replace_once(root / "app/build.gradle.kts", SIGNING, '            versionNameSuffix = "-foss"\n', "SABLE_KEYMAPPER_SIGNING")
    replace_once(root / "settings.gradle.kts", BINTRAY, "", "SABLE_KEYMAPPER_BINTRAY")
    # Sets android:icon="@mipmap/ic_sable_keymapper" and android:roundIcon="@mipmap/ic_sable_keymapper_round" on <application>.
    # Icon generated by sable-src/tools/gen_first_party_icons.py (row keymapper); "@string/app_name" stays.
    icons = set_sable_app_icon(pathlib.Path(__file__).resolve().parent / "res", root / "app", "ic_sable_keymapper", "SABLE_KEYMAPPER")
    print(f"SABLE_KEYMAPPER_FLAVOR=PASS icons={icons}")


if __name__ == "__main__":
    main()
