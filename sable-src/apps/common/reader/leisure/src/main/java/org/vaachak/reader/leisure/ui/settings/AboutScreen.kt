/**
 * About page. Text only: Sable Reader makes no network requests, so there are no outbound links.
 * Upstream license attribution is preserved here and in docs/P5_READER_SOURCE_PROVENANCE.md.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun AboutScreen(
    onBack: () -> Unit
) {
    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("About Sable Reader") },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "Back")
                    }
                }
            )
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .padding(padding)
                .fillMaxSize()
                .verticalScroll(rememberScrollState())
                .padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(16.dp)
        ) {
            AboutCard("Sable Reader", "Version ${BuildConfig.VERSION_NAME} (${BuildConfig.VERSION_CODE})")
            AboutCard(
                "Private by design",
                "Your library, reading progress, bookmarks and highlights stay on this device. " +
                    "Sable Reader has no account, no analytics and no network access."
            )
            AboutCard(
                "Open source",
                "Based on Vaachak Mobile (MIT License, © 2026 Piyush Daiya) and the Readium Kotlin Toolkit " +
                    "(BSD-3-Clause). Upstream copyright and license notices are preserved in the source."
            )
        }
    }
}

@Composable
private fun AboutCard(title: String, body: String) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant)
    ) {
        Column(modifier = Modifier.padding(16.dp), verticalArrangement = Arrangement.spacedBy(8.dp)) {
            Text(title, style = MaterialTheme.typography.titleMedium, fontWeight = FontWeight.Bold)
            Text(body, style = MaterialTheme.typography.bodyMedium)
        }
    }
}
