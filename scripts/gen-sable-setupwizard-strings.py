#!/usr/bin/env python3
"""Regenerate the SableSetupWizardOverlay strings from a LineageOS SetupWizard
checkout (packages/apps/SetupWizard, lineage-23.2).

Rule (DESIGN-KF-B "Branding", as on SableOS Panther): the owner Setup flow
shows no LineageOS name; package ids, legal and licence text and upstream URLs
stay. The overlay therefore replaces only these visible strings:

  setup_welcome_message   "Welcome to SableOS", in every locale LineageOS
                          translates (the product name fills %1$s).
  intro_restore_subtitle  English (default and en-r*): the SableOS Panther
                          wording. Other translated locales: the LineageOS
                          translation with SableOS in place of the OS name
                          ("a Seedvault backup from SableOS or any other OS").
  update_recovery_title, update_recovery_description, update_recovery_setting
                          neutral "recovery" wording, English only (default
                          and en-r*): no Sable translations exist yet, so
                          other locales keep the LineageOS translation. The
                          step is shown only when /vendor/bin/install-recovery.sh
                          exists, which the A/B Q25 does not ship.

`os_name`, the LineageOS features page and its privacy-policy text are never
overlaid (0408 removes that page from the owner flow).

    python3 scripts/gen-sable-setupwizard-strings.py <SetupWizard checkout>
"""
import pathlib
import re
import sys

PRODUCT = "SableOS"
OUT = pathlib.Path(__file__).resolve().parents[1] / "product/common/overlay/SableSetupWizardOverlay/res"
# Translations write the argument as <xliff:g>%1$s</xliff:g>, <xliff:g>%1s</xliff:g>,
# <xliff:g>%s</xliff:g>, a self-closing <xliff:g/> or a bare %1$s / %s.
ARG = re.compile(r'<xliff:g[^>]*>%(?:1\$?)?s</xliff:g>|<xliff:g[^>]*/>|%1\$s|%s')
FILLED = ("setup_welcome_message", "intro_restore_subtitle")

ENGLISH = {
    "intro_restore_subtitle": "If you have a compatible Seedvault backup from a previous device, you can restore it here.",
    "update_recovery_title": "Update recovery",
    "update_recovery_description": "Updates the recovery on the first boot after every system update.",
    "update_recovery_setting": "Update recovery alongside the system",
}
ORDER = ("setup_welcome_message", "intro_restore_subtitle", "update_recovery_title",
         "update_recovery_description", "update_recovery_setting")

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/gen-sable-setupwizard-strings.py from LineageOS SetupWizard
     (lineage-23.2) translations. Do not edit by hand. -->
<resources>
"""


def upstream(strings: pathlib.Path) -> dict[str, str]:
    out = {}
    for line in strings.read_text(encoding="utf-8").splitlines():
        m = re.search(r'<string name="(\w+)"[^>]*>(.*)</string>', line)
        if m and m.group(1) in FILLED:
            text, n = ARG.subn(PRODUCT, m.group(2))
            if n != 1:
                raise SystemExit(f"{strings}: expected one argument in {m.group(2)!r}")
            if re.search("lineage", text, re.I):
                raise SystemExit(f"{strings}: {m.group(1)} still names LineageOS: {text!r}")
            out[m.group(1)] = text
    return out


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    res = pathlib.Path(sys.argv[1]) / "res"
    count = 0
    for strings in sorted(res.glob("values*/strings.xml")):
        qualifier = strings.parent.name
        if qualifier != "values" and not re.fullmatch(r"values-[a-z]{2,3}(-r[A-Z]{2})?", qualifier):
            continue
        found = upstream(strings)
        if not found:
            continue
        if qualifier == "values" or qualifier.startswith("values-en-"):
            found.update(ENGLISH)
        out = OUT / qualifier / "strings.xml"
        out.parent.mkdir(parents=True, exist_ok=True)
        body = "".join(f'    <string name="{k}">{found[k]}</string>\n' for k in ORDER if k in found)
        out.write_text(HEADER + body + "</resources>\n", encoding="utf-8")
        count += 1
    print(f"SETUPWIZARD_STRING_LOCALES={count}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
